const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");

function resolveSha() {
  const fromEnv =
    process.env.SOURCE_COMMIT ||
    process.env.COOLIFY_BRANCH_COMMIT_SHA ||
    process.env.GITHUB_SHA ||
    "";
  if (fromEnv) return fromEnv.slice(0, 12);
  try {
    return execSync("git rev-parse --short HEAD", { encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}

const sha = resolveSha();
const builtAt = new Date().toISOString();
const out = path.join(__dirname, "..", "lib", "build-info.generated.ts");

fs.writeFileSync(
  out,
  `/** Auto-generated by scripts/generate-build-info.js — do not edit */\n` +
    `export const BUILD_SHA = ${JSON.stringify(sha)};\n` +
    `export const BUILD_TIME = ${JSON.stringify(builtAt)};\n`
);

console.log(`[build-info] sha=${sha} builtAt=${builtAt}`);
